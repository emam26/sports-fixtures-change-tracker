/*
    PostgreSQL schema for the cloud deployment path.

    This keeps the twelve logical application tables and their provider-owned
    identity/provenance relationships. It is intentionally separate from the
    SQL Server script; it must be reviewed and applied manually by the owner.
    Timestamps are stored as timestamptz and the application supplies UTC values.
    checkpoint_version replaces SQL Server rowversion with an application-owned
    monotonic version incremented atomically by the checkpoint upsert.
*/

BEGIN;

CREATE TABLE IF NOT EXISTS schema_migrations
(
    version varchar(100) PRIMARY KEY,
    applied_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS competitions
(
    competition_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider varchar(50) NOT NULL,
    provider_shortcut varchar(50) NOT NULL,
    competition_name varchar(200) NOT NULL,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_competitions_provider_shortcut UNIQUE (provider, provider_shortcut),
    CONSTRAINT ck_competitions_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_competitions_shortcut_not_blank CHECK (btrim(provider_shortcut) <> ''),
    CONSTRAINT ck_competitions_name_not_blank CHECK (btrim(competition_name) <> '')
);

CREATE TABLE IF NOT EXISTS competition_seasons
(
    competition_season_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_id bigint NOT NULL REFERENCES competitions (competition_id),
    source_league_id integer NOT NULL,
    season_start_year smallint NOT NULL,
    season_label varchar(20),
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_competition_seasons_identity
        UNIQUE (competition_id, source_league_id, season_start_year),
    CONSTRAINT ck_competition_seasons_league_id_positive CHECK (source_league_id > 0),
    CONSTRAINT ck_competition_seasons_year_range
        CHECK (season_start_year BETWEEN 1900 AND 2200)
);

CREATE TABLE IF NOT EXISTS teams
(
    team_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider varchar(50) NOT NULL,
    provider_team_id bigint NOT NULL,
    team_name varchar(200) NOT NULL,
    short_name varchar(100),
    tla varchar(20),
    team_group_name varchar(200),
    team_icon_url varchar(2048),
    wikidata_id varchar(100),
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_teams_provider_team UNIQUE (provider, provider_team_id),
    CONSTRAINT ck_teams_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_teams_provider_id_positive CHECK (provider_team_id > 0),
    CONSTRAINT ck_teams_name_not_blank CHECK (btrim(team_name) <> '')
);

CREATE TABLE IF NOT EXISTS source_snapshots
(
    source_snapshot_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider varchar(50) NOT NULL,
    provider_shortcut varchar(50) NOT NULL,
    source_league_id integer NOT NULL,
    season_start_year smallint NOT NULL,
    matchday_number integer,
    competition_stage varchar(100),
    source_url varchar(2048) NOT NULL,
    retrieved_at_utc timestamptz(6) NOT NULL,
    http_status smallint NOT NULL,
    content_type varchar(255),
    byte_count bigint NOT NULL,
    sha256 char(64) NOT NULL,
    local_directory varchar(750) NOT NULL,
    response_path varchar(2048) NOT NULL,
    metadata_path varchar(2048) NOT NULL,
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_source_snapshots_local_directory UNIQUE (provider, local_directory),
    CONSTRAINT ck_source_snapshots_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_source_snapshots_shortcut_not_blank
        CHECK (btrim(provider_shortcut) <> ''),
    CONSTRAINT ck_source_snapshots_league_id_positive CHECK (source_league_id > 0),
    CONSTRAINT ck_source_snapshots_year_range
        CHECK (season_start_year BETWEEN 1900 AND 2200),
    CONSTRAINT ck_source_snapshots_matchday_positive
        CHECK (matchday_number IS NULL OR matchday_number > 0),
    CONSTRAINT ck_source_snapshots_http_status CHECK (http_status BETWEEN 100 AND 599),
    CONSTRAINT ck_source_snapshots_byte_count CHECK (byte_count >= 0),
    CONSTRAINT ck_source_snapshots_sha256_length CHECK (length(sha256) = 64)
);

CREATE TABLE IF NOT EXISTS matches
(
    match_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    competition_season_id bigint NOT NULL REFERENCES competition_seasons,
    provider varchar(50) NOT NULL,
    provider_match_id bigint NOT NULL,
    home_team_id bigint NOT NULL REFERENCES teams,
    away_team_id bigint NOT NULL REFERENCES teams,
    matchday_number integer,
    competition_stage varchar(100),
    source_group_id bigint,
    source_group_order_id integer,
    source_group_name varchar(200),
    kickoff_utc timestamptz(6),
    source_match_is_finished boolean NOT NULL,
    source_last_update_utc timestamptz(6),
    source_last_update_raw varchar(64),
    source_time_zone_id varchar(128),
    location varchar(256),
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_matches_provider_match UNIQUE (provider, provider_match_id),
    CONSTRAINT ck_matches_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_matches_provider_id_positive CHECK (provider_match_id > 0),
    CONSTRAINT ck_matches_distinct_teams CHECK (home_team_id <> away_team_id),
    CONSTRAINT ck_matches_matchday_positive
        CHECK (matchday_number IS NULL OR matchday_number > 0),
    CONSTRAINT ck_matches_source_group_order_positive
        CHECK (source_group_order_id IS NULL OR source_group_order_id > 0)
);

CREATE TABLE IF NOT EXISTS match_results
(
    match_result_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id bigint NOT NULL REFERENCES matches,
    provider varchar(50) NOT NULL,
    provider_result_id bigint NOT NULL,
    result_type_id integer,
    result_type_kind varchar(100) NOT NULL,
    result_order_id integer,
    result_name varchar(200),
    result_description varchar(500),
    points_team1 integer,
    points_team2 integer,
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_match_results_match_result UNIQUE (match_id, provider_result_id),
    CONSTRAINT uq_match_results_match_type UNIQUE (match_id, result_type_kind),
    CONSTRAINT ck_match_results_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_match_results_provider_id_positive CHECK (provider_result_id > 0),
    CONSTRAINT ck_match_results_type_not_blank CHECK (btrim(result_type_kind) <> ''),
    CONSTRAINT ck_match_results_score_pair CHECK (
        (points_team1 IS NULL AND points_team2 IS NULL)
        OR (points_team1 IS NOT NULL AND points_team2 IS NOT NULL)
    ),
    CONSTRAINT ck_match_results_scores_nonnegative CHECK (
        (points_team1 IS NULL OR points_team1 >= 0)
        AND (points_team2 IS NULL OR points_team2 >= 0)
    )
);

CREATE TABLE IF NOT EXISTS match_goals
(
    match_goal_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id bigint NOT NULL REFERENCES matches,
    provider varchar(50) NOT NULL,
    provider_goal_id bigint NOT NULL,
    score_team1 integer,
    score_team2 integer,
    match_minute integer,
    goal_getter_provider_id bigint,
    goal_getter_name varchar(200),
    scoring_team_id bigint REFERENCES teams,
    is_penalty boolean,
    is_own_goal boolean,
    is_overtime boolean,
    comment varchar(1000),
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_match_goals_match_goal UNIQUE (match_id, provider_goal_id),
    CONSTRAINT ck_match_goals_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_match_goals_provider_id_positive CHECK (provider_goal_id > 0),
    CONSTRAINT ck_match_goals_scores_nonnegative CHECK (
        (score_team1 IS NULL OR score_team1 >= 0)
        AND (score_team2 IS NULL OR score_team2 >= 0)
    ),
    CONSTRAINT ck_match_goals_minute_nonnegative
        CHECK (match_minute IS NULL OR match_minute >= 0)
);

CREATE TABLE IF NOT EXISTS import_runs
(
    import_run_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider varchar(50) NOT NULL,
    competition_season_id bigint REFERENCES competition_seasons,
    source_snapshot_id bigint REFERENCES source_snapshots,
    matchday_number integer,
    competition_stage varchar(100),
    requested_url varchar(2048),
    started_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at_utc timestamptz(6),
    status varchar(20) NOT NULL DEFAULT 'Started',
    is_replay boolean NOT NULL DEFAULT FALSE,
    replay_of_import_run_id bigint REFERENCES import_runs,
    matches_seen integer NOT NULL DEFAULT 0,
    matches_inserted integer NOT NULL DEFAULT 0,
    matches_updated integer NOT NULL DEFAULT 0,
    matches_unchanged integer NOT NULL DEFAULT 0,
    matches_rejected integer NOT NULL DEFAULT 0,
    results_seen integer NOT NULL DEFAULT 0,
    validation_issue_count integer NOT NULL DEFAULT 0,
    failure_phase varchar(100),
    error_summary varchar(4000),
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_import_runs_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_import_runs_matchday_positive
        CHECK (matchday_number IS NULL OR matchday_number > 0),
    CONSTRAINT ck_import_runs_status
        CHECK (status IN ('Started', 'Succeeded', 'Failed', 'RolledBack', 'Skipped')),
    CONSTRAINT ck_import_runs_completed_after_started
        CHECK (completed_at_utc IS NULL OR completed_at_utc >= started_at_utc),
    CONSTRAINT ck_import_runs_counts_nonnegative CHECK (
        matches_seen >= 0 AND matches_inserted >= 0 AND matches_updated >= 0
        AND matches_unchanged >= 0 AND matches_rejected >= 0
        AND results_seen >= 0 AND validation_issue_count >= 0
    ),
    CONSTRAINT ck_import_runs_replay_parent CHECK (
        (is_replay = FALSE AND replay_of_import_run_id IS NULL)
        OR (is_replay = TRUE AND replay_of_import_run_id IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS validation_issues
(
    validation_issue_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    import_run_id bigint REFERENCES import_runs,
    source_snapshot_id bigint REFERENCES source_snapshots,
    provider varchar(50) NOT NULL,
    source_record_type varchar(100),
    source_record_id varchar(100),
    field_name varchar(128),
    issue_code varchar(100) NOT NULL,
    severity varchar(20) NOT NULL,
    issue_message varchar(2000) NOT NULL,
    source_value varchar(4000),
    is_resolved boolean NOT NULL DEFAULT FALSE,
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_validation_issues_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_validation_issues_code_not_blank CHECK (btrim(issue_code) <> ''),
    CONSTRAINT ck_validation_issues_message_not_blank CHECK (btrim(issue_message) <> ''),
    CONSTRAINT ck_validation_issues_severity CHECK (severity IN ('Info', 'Warning', 'Error'))
);

CREATE TABLE IF NOT EXISTS match_changes
(
    match_change_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id bigint NOT NULL REFERENCES matches,
    import_run_id bigint NOT NULL REFERENCES import_runs,
    source_snapshot_id bigint NOT NULL REFERENCES source_snapshots,
    field_name varchar(128) NOT NULL,
    change_kind varchar(20) NOT NULL,
    old_value text,
    new_value text,
    observed_at_utc timestamptz(6) NOT NULL,
    source_last_update_utc timestamptz(6),
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_match_changes_snapshot_match_field
        UNIQUE (source_snapshot_id, match_id, field_name, change_kind),
    CONSTRAINT ck_match_changes_field_not_blank CHECK (btrim(field_name) <> ''),
    CONSTRAINT ck_match_changes_kind CHECK (change_kind IN ('Inserted', 'Updated', 'Removed')),
    CONSTRAINT ck_match_changes_value_for_insert CHECK (
        change_kind <> 'Inserted' OR (old_value IS NULL AND new_value IS NOT NULL)
    )
);

CREATE TABLE IF NOT EXISTS sync_checkpoints
(
    sync_checkpoint_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider varchar(50) NOT NULL,
    competition_season_id bigint NOT NULL REFERENCES competition_seasons,
    scope_key varchar(250) NOT NULL,
    matchday_number integer,
    competition_stage varchar(100),
    last_successful_snapshot_id bigint REFERENCES source_snapshots,
    last_successful_import_run_id bigint REFERENCES import_runs,
    last_source_update_utc timestamptz(6),
    last_processed_at_utc timestamptz(6),
    updated_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    checkpoint_version bigint NOT NULL DEFAULT 1,
    source_checkpoint_version bytea,
    CONSTRAINT uq_sync_checkpoints_provider_scope UNIQUE (provider, scope_key),
    CONSTRAINT ck_sync_checkpoints_provider_not_blank CHECK (btrim(provider) <> ''),
    CONSTRAINT ck_sync_checkpoints_scope_not_blank CHECK (btrim(scope_key) <> ''),
    CONSTRAINT ck_sync_checkpoints_matchday_positive
        CHECK (matchday_number IS NULL OR matchday_number > 0),
    CONSTRAINT ck_sync_checkpoints_version_positive CHECK (checkpoint_version > 0)
);

CREATE TABLE IF NOT EXISTS match_notes
(
    match_note_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id bigint NOT NULL REFERENCES matches,
    note_text varchar(4000) NOT NULL,
    created_by varchar(256),
    is_archived boolean NOT NULL DEFAULT FALSE,
    created_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_match_notes_text_not_blank CHECK (btrim(note_text) <> '')
);

/* A database lease prevents overlapping GitHub Actions jobs and manual syncs. */
CREATE TABLE IF NOT EXISTS sync_leases
(
    lease_key varchar(200) PRIMARY KEY,
    owner_token varchar(200) NOT NULL,
    acquired_at_utc timestamptz(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at_utc timestamptz(6) NOT NULL,
    CONSTRAINT ck_sync_leases_expiry CHECK (expires_at_utc > acquired_at_utc)
);

CREATE INDEX IF NOT EXISTS ix_competition_seasons_source_lookup
    ON competition_seasons (source_league_id, season_start_year);
CREATE INDEX IF NOT EXISTS ix_teams_name ON teams (team_name);
CREATE INDEX IF NOT EXISTS ix_matches_competition_kickoff
    ON matches (competition_season_id, kickoff_utc);
CREATE INDEX IF NOT EXISTS ix_matches_home_team_kickoff ON matches (home_team_id, kickoff_utc);
CREATE INDEX IF NOT EXISTS ix_matches_away_team_kickoff ON matches (away_team_id, kickoff_utc);
CREATE INDEX IF NOT EXISTS ix_matches_matchday_stage
    ON matches (competition_season_id, matchday_number, competition_stage);
CREATE INDEX IF NOT EXISTS ix_match_results_match_type
    ON match_results (match_id, result_type_kind);
CREATE INDEX IF NOT EXISTS ix_match_goals_match_minute ON match_goals (match_id, match_minute);
CREATE INDEX IF NOT EXISTS ix_source_snapshots_scope_retrieved
    ON source_snapshots (provider, source_league_id, season_start_year,
                         matchday_number, retrieved_at_utc DESC);
CREATE INDEX IF NOT EXISTS ix_source_snapshots_hash
    ON source_snapshots (provider, sha256, retrieved_at_utc);
CREATE INDEX IF NOT EXISTS ix_import_runs_scope_started
    ON import_runs (competition_season_id, matchday_number, started_at_utc DESC);
CREATE INDEX IF NOT EXISTS ix_import_runs_status_started
    ON import_runs (status, started_at_utc DESC);
CREATE INDEX IF NOT EXISTS ix_import_runs_snapshot ON import_runs (source_snapshot_id);
CREATE INDEX IF NOT EXISTS ix_validation_issues_import
    ON validation_issues (import_run_id, severity, created_at_utc DESC);
CREATE INDEX IF NOT EXISTS ix_validation_issues_snapshot_record
    ON validation_issues (source_snapshot_id, source_record_type, source_record_id);
CREATE INDEX IF NOT EXISTS ix_match_changes_history ON match_changes (match_id, observed_at_utc DESC);
CREATE INDEX IF NOT EXISTS ix_match_changes_import
    ON match_changes (import_run_id, observed_at_utc DESC);
CREATE INDEX IF NOT EXISTS ix_sync_checkpoints_lookup
    ON sync_checkpoints (competition_season_id, matchday_number, competition_stage);
CREATE INDEX IF NOT EXISTS ix_match_notes_match_updated
    ON match_notes (match_id, updated_at_utc DESC);

INSERT INTO schema_migrations (version)
VALUES ('001_initial_schema')
ON CONFLICT (version) DO NOTHING;

COMMIT;
